"""The registry of compiler error codes, docs/error-codes.md.

Every place in lib/ that raises an error to the user carries a literal code,
`(H 3012)', printed as H3012.  This script reads those literals and writes
the registry: code, kind, source file, and how the message begins.

    python3 scripts/error-codes.py            write docs/error-codes.md
    python3 scripts/error-codes.py --check    exit 1 if it is not current

Both runs refuse a code that stands twice, a code outside 1..9998 (H9999 is
the internal error's, set in lib/Error.ml), and a code that is both in use
and retired.  A code that leaves the compiler is not dropped: the next write
moves it to the retired table with its last message, and a retired code is
never given again.  That is what makes a code stable -- it names one message
for as long as the registry exists.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "docs", "error-codes.md")

KINDS = {
    "GenericError": "Generic Error",
    "ParseError": "Parse Error",
    "CliError": "Command Line Arguments Error",
    "TypeError": "Type Error",
    "LinearityError": "Linearity Error",
    "DeclarationError": "Declaration Error",
    "EntrypointError": "Entrypoint Definition Error",
    "InternalError": "Internal Error",
}

HEADER = """# Compiler error codes

Generated by `scripts/error-codes.py` from the literal codes in `lib/` and, for
the package tool, in `pkg/src`; do
not edit by hand.  The checks run `python3 scripts/error-codes.py --check`
which fails when this file is not what the compiler holds.

Every error the compiler reports carries a code: in the text output as
`Error code: H3012`, in `--error-format=json` (rustc's form) as
`"code": {"code": "H3012", "explanation": null}`, in
`--error-format=hilde-json` as `"code": "H3012"`.  A code names ONE place in the compiler that raises, so it stays the same
when the wording of the message changes, and it is never given to another
message: a code that leaves the compiler moves to the retired table below.

The first digit says the kind the error had when its code was given: 0
parse, 1 command line, 2 declaration, 3 type, 4 linearity, 5 entrypoint,
6 generic, 7 `@template`, 8 SQL (`@query`, `@execute`, migrations), 9
internal.  H9999 is every internal error -- a bug in the compiler, not in
the program.  "Message begins" is the first string literal at the raise
site; where it is a format, `%s` and `%d` stand for what the compiler fills
in.

"""


def strip_comments(text):
    """Blank out OCaml comments, keeping offsets; strings stay as they are,
    and a comment opener inside a string is not one."""
    out = list(text)
    i, n, depth = 0, len(text), 0
    while i < n:
        if depth == 0 and text[i] == '"':
            i = skip_string(text, i)
            continue
        if depth == 0 and text[i] == "'" and re.match(r"'(\\.|[^\\'])'", text[i:i + 4]):
            i += len(re.match(r"'(\\.|[^\\'])'", text[i:i + 4]).group(0))
            continue
        if text.startswith("(*", i):
            depth += 1
            out[i] = out[i + 1] = " "
            i += 2
            continue
        if depth > 0:
            if text.startswith("*)", i):
                depth -= 1
                out[i] = out[i + 1] = " "
                i += 2
                continue
            if text[i] == '"':
                j = skip_string(text, i)
                for k in range(i, j):
                    if out[k] != "\n":
                        out[k] = " "
                i = j
                continue
            if out[i] != "\n":
                out[i] = " "
        i += 1
    return "".join(out)


def skip_string(text, i):
    j = i + 1
    while text[j] != '"':
        j += 2 if text[j] == "\\" else 1
    return j + 1


def ocaml_string(literal):
    body = literal[1:-1]
    body = re.sub(r"\\\n\s*", "", body)
    return body.replace('\\"', '"').replace("\\\\", "\\").replace("\\n", " ")


def list_message(text, i):
    """An error text written as a list, `[Text "..."; Code x; Break; ...]':
    its literal pieces as they are, anything computed as `...'."""
    parts, depth, start = [], 0, i
    while i < len(text):
        c = text[i]
        if c == '"':
            i = skip_string(text, i)
            continue
        if c in "([{":
            depth += 1
        elif c in ")}" or (c == "]" and depth > 0):
            depth -= 1
        elif c == "]" or (c == ";" and depth == 0):
            parts.append(text[start:i].strip())
            if c == "]":
                break
            start = i + 1
        i += 1
    return "".join(element(p) for p in parts)


STRING = r'"(?:\\.|[^"\\])*"'


def element(p):
    """One piece of an error text: a literal as it is, `Text ("a" ^ x)' as
    `a...', a line break as a space, anything else as `...'."""
    p = p.strip()
    m = re.fullmatch(r"(Text|Code)\s+(" + STRING + ")", p, re.S)
    if m:
        return ocaml_string(m.group(2))
    m = re.fullmatch(r"(Text|Code)\s+\((.*)\)", p, re.S)
    if m:
        pieces = re.findall(STRING + r"|[^\^\"]+", m.group(2))
        return "".join(ocaml_string(x) if x.startswith('"') else "..."
                       for x in pieces if x.strip() and x.strip() != "^")
    if p == "Break":
        return " "
    return "..." if p else ""


def matching_paren(text, i):
    depth = 0
    while i < len(text):
        if text[i] == '"':
            i = skip_string(text, i)
            continue
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text) - 1


def bound_message(text, name, site):
    """The message of `hilde_raise ... <name>', where <name> is bound a few
    lines above: the pieces before a `::', then the first list after it."""
    b = text.rfind("let " + name + " =", max(0, site - 1500), site)
    if b < 0:
        return ""
    expr = text[b + len("let " + name + " ="):site]
    out = ""
    head = re.match(r"\s*((?:Text|Code)\s+(?:" + STRING + r"|\([^()]*\)))\s*::", expr, re.S)
    if head:
        out = element(head.group(1)) + " "
    k = expr.find("[")
    if k >= 0:
        out += list_message(expr, k + 1)
    return out


def sites():
    found = []
    lib = os.path.join(ROOT, "lib")
    for name in sorted(os.listdir(lib)):
        if not (name.endswith(".ml") or name.endswith(".mll")):
            continue
        text = strip_comments(open(os.path.join(lib, name)).read())
        matches = list(re.finditer(r"\(H (\d+)\)", text))
        for k, m in enumerate(matches):
            end = matches[k + 1].start() if k + 1 < len(matches) else len(text)
            after = text[m.end():min(end, m.end() + 2000)]
            kind = "Generic Error"
            km = re.match(r"\s*(?:[a-z_]+\s+)?([A-Z][A-Za-z]*Error)\b", after)
            if km and km.group(1) in KINDS:
                kind = KINDS[km.group(1)]
            lm = re.match(r"\s*(?:[a-z_]+\s+)?(?:[A-Z][A-Za-z]*Error\s+)?\[", after)
            vm = re.match(r"\s*[A-Z][A-Za-z]*Error\s+([a-z_]+)\s*$", after.split("\n")[0])
            cm = re.match(r"(\s*(?:[a-z_.]+\s+)*)\(\s*" + STRING + r"\s*\^", after)
            if lm:
                message = list_message(after, lm.end())
            elif cm:
                open_at = len(cm.group(1))
                message = element("Text " + after[open_at:matching_paren(after, open_at) + 1])
            elif vm:
                message = bound_message(text, vm.group(1), m.start())
            else:
                sm = re.search(r'"(?:\\.|[^"\\])*"', after)
                message = ocaml_string(sm.group(0)) if sm else ""
            message = " ".join(message.split())
            message = re.sub(r"(\.\.\.)+", "...", message)
            if len(message) > 90:
                message = message[:87].rstrip() + "..."
            found.append((int(m.group(1)), kind, "lib/" + name, message))
    return found + package_sites() + sperli_sites()


def package_sites():
    """The codes of the package tool hilde-pkg, H1500 to H1599, from its
    sources in pkg/src: a code is the first number of a call, (15nn, and
    names a kind of problem, so it may stand at several places; the first
    place by file name is the one listed, with the first string after it."""
    found = {}
    pkg = os.path.join(ROOT, "pkg", "src")
    if not os.path.isdir(pkg):
        return []
    for name in sorted(os.listdir(pkg)):
        if not name.endswith(".hiq") or name.endswith(".test.hiq"):
            continue
        for line in open(os.path.join(pkg, name), encoding="utf-8"):
            m = re.search(r"\((15\d\d),", line)
            if not m or int(m.group(1)) in found:
                continue
            sm = re.search(r'"((?:\\.|[^"\\])*)"', line[m.end():])
            message = " ".join((sm.group(1) if sm else "...").split())
            if len(message) > 90:
                message = message[:87].rstrip() + "..."
            found[int(m.group(1))] = (int(m.group(1)), "Package Error", "pkg/src/" + name, message)
    return [found[c] for c in sorted(found)]


def sperli_sites():
    """The codes of a Sperli job, H1601 to H1699, from the table of words in
    standard/src/SperliError.hiq: a branch `if code = 16nn then` and the
    string it returns."""
    path = os.path.join(ROOT, "standard", "src", "SperliError.hiq")
    if not os.path.isfile(path):
        return []
    found = []
    pending = None
    for line in open(path, encoding="utf-8"):
        m = re.search(r"if code = (16\d\d) then", line)
        if m:
            pending = int(m.group(1))
            continue
        sm = re.search(r'return "((?:\\.|[^"\\])*)";', line)
        if pending is not None and sm:
            message = " ".join(sm.group(1).split())
            found.append((pending, "Sperli Error", "standard/src/SperliError.hiq", message))
            pending = None
    return found


def cell(s):
    return s.replace("|", "\\|").replace("`", "'")


def read_registry():
    """The codes of the existing registry: current and retired, each with
    its row, so that a code that left the compiler can be retired."""
    current, retired = {}, {}
    if not os.path.exists(REGISTRY):
        return current, retired
    table = None
    for line in open(REGISTRY):
        if line.startswith("## "):
            table = "retired" if line.startswith("## Retired") else "current"
        m = re.match(r"\| (H\d{4}) \|(.*)\|\s*$", line)
        if m and table:
            cells = [c.strip() for c in m.group(2).split(" | ")]
            (retired if table == "retired" else current)[m.group(1)] = cells
    return current, retired


def render(found, retired):
    lines = [HEADER, "## In use\n\n",
             "| Code | Kind | Raised in | Message begins |\n",
             "|---|---|---|---|\n"]
    for code, kind, path, message in sorted(found):
        lines.append("| H%04d | %s | `%s` | %s |\n" % (code, kind, path, cell(message)))
    lines.append("| H9999 | Internal Error | `lib/Error.ml` | Internal compiler error: ... |\n")
    lines.append("\n## Retired\n\nA code here is not given again.\n\n")
    lines.append("| Code | Kind | Raised in | Last message |\n|---|---|---|---|\n")
    for code in sorted(retired):
        kind, path, message = (retired[code] + ["", "", ""])[:3]
        lines.append("| %s | %s | %s | %s |\n" % (code, kind, path, message))
    if not retired:
        lines.append("| -- | | | none yet |\n")
    return "".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    found = sites()
    problems = []
    seen = {}
    for code, kind, path, message in found:
        if not 1 <= code <= 9998:
            problems.append("H%04d in %s: a code is 1..9998, H9999 is the internal error's" % (code, path))
        if code in seen:
            problems.append("H%04d stands twice: %s and %s" % (code, seen[code], path))
        seen[code] = path
    old_current, retired = read_registry()
    in_use = {"H%04d" % c for c in seen} | {"H9999"}
    for code in sorted(in_use & set(retired)):
        problems.append("%s is retired and may not be given again" % code)
    for code, cells in old_current.items():
        if code not in in_use and code not in retired:
            retired[code] = cells
    for p in problems:
        print("error-codes: " + p)
    text = render(found, retired)
    ok = not problems
    if check:
        current = os.path.exists(REGISTRY) and open(REGISTRY).read() == text
        print("error-codes: sites=%d codes=%d retired=%d registry=%s"
              % (len(found), len(seen) + 1, len(retired), "current" if current else "STALE"))
        if not current:
            print("error-codes: run `python3 scripts/error-codes.py' and commit docs/error-codes.md")
        ok = ok and current
    elif ok:
        open(REGISTRY, "w").write(text)
        print("error-codes: wrote %s: %d codes in use, %d retired"
              % (os.path.relpath(REGISTRY, ROOT), len(seen) + 1, len(retired)))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
