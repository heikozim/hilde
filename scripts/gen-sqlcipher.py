def die(message):
    print("ABORT: " + message, file=sys.stderr)
    sys.exit(9)


def transform(text, edits, source, module):
    for old, new, count in edits:
        if old == "HEAD":
            m = re.search(r"^module (?:Standard|Bindings)[.]", text, re.M)
            d = re.search(r'^"""\n.*?^"""\n', text[:m.start()], re.M | re.S) if m else None
            if d is None:
                die("%s: no head before the module line" % source)
            text = text[:d.start()] + new + text[d.end():]
            continue
        n = text.count(old)
        if n != count:
            die("%s: expected %d occurrence(s), found %d, of:\n%s" % (source, count, n, old[:200]))
        text = text.replace(old, new)
    # Its own name in the messages it prints.
    text = text.replace('"Standard.Sqlite: ', '"Standard.SqlCipher: ')
    lines = text.split("\n")
    # The licence header stays first; the banner follows it.  Standard.Sqlite
    # has no Austral predecessor, so its head is Hilde's licence header and
    # not the modification notice: it ends with the
    # SPDX-License-Identifier line and the bare `--' after it.
    end = None
    for i, line in enumerate(lines[:10]):
        if line.startswith("-- SPDX-License-Identifier: "):
            end = i + 1
            break
    if end is None:
        die("%s: no licence header in the first ten lines" % source)
    if end < len(lines) and lines[end] == "--":
        end += 1
    return "\n".join(lines[:end]) + "\n" + (BANNER % (source, module)) + "\n".join(lines[end:])


def main():
    check = "--check" in sys.argv[1:]
    differ = 0
    for source, target, module, edits in JOBS:
        with open(os.path.join(SRC, source), encoding="ascii") as f:
            text = transform(f.read(), edits, source, module)
        path = os.path.join(SRC, target)
        if check:
            try:
                with open(path, encoding="ascii") as f:
                    current = f.read()
            except OSError:
                current = None
            if current != text:
                print("gen-sqlcipher --check: %s is NOT current" % os.path.relpath(path, ROOT))
                differ += 1
        else:
            with open(path, "w", encoding="ascii", newline="\n") as f:
                f.write(text)
            print("wrote %s (%d bytes)" % (os.path.relpath(path, ROOT), len(text)))
    if check:
        if differ:
            sys.exit(1)
        print("gen-sqlcipher --check: Standard.SqlCipher and Bindings.SqlCipher are current (4 files)")
    sys.exit(0)


if __name__ == "__main__":
    main()
