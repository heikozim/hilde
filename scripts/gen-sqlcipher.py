#!/usr/bin/env python3
"""Write Standard.SqlCipher and Bindings.SqlCipher from Standard.Sqlite and
Bindings.Sqlite.

    python3 scripts/gen-sqlcipher.py            write the four files
    python3 scripts/gen-sqlcipher.py --check    write nothing, compare

The IMPORT picks the library -- Standard.Sqlite links
libsqlite3, Standard.SqlCipher libsqlcipher -- and the price is that the
two modules are the same code except for the binding they import and the
key.  Hilde has no way to write one module over two bindings, so the second
one is GENERATED from the first, here, and the gate runs `--check': a
change to Standard.Sqlite that is not carried into Standard.SqlCipher turns
it red, instead of the two drifting apart without a word.

Each is two modules: the binding (standard/src/Bindings/),
which holds every address and C call, and the safe module a programme
imports.  Both SqlCipher files of each layer are generated from the Sqlite
files of the same layer.

Every change below is a replacement of text that must occur EXACTLY as
written, the number of times given; anything else stops the script.  So a
change to the part of a source a replacement anchors on stops it too, and
the replacement is looked at again rather than applied to something it was
not written for.

Exit 0 written (or, under --check, current), 1 --check found a difference,
9 could not run.
"""
