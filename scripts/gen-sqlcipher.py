KEY_INTERFACE = '''    """
    The key of an encrypted database.  It is linear: it is made from bytes,
    consumed by the open it is given to, and its copy of the bytes is wiped
    with explicit_bzero as soon as SQLCipher has taken them.  No function
    reads it back, copies it or prints it.
    """
    type Key: Linear;

    """
    A key from bytes; SQLCipher derives the database key from them with its
    default key derivation.  The bytes are copied, and the caller's own are
    the caller's to wipe.
    No contract: the key is opaque, and the open refuses an empty one.
    """
    generic [R: Region]
    function makeKey(bytes: Span[Nat8, R]): Key;

    """
    Wipes and gives back a key that was not used.
    No contract: it only wipes and frees.
    """
    function forgetKey(key: Key): Unit;

'''

KEY_BODY = '''    ---
    --- The key
    ---

    record Key: Linear is
        bytes: Pointer[Nat8];
        size: Index;
    end;

    generic [R: Region]
    function makeKey(bytes: Span[Nat8, R]): Key is
        let size: Index := spanLength(bytes);
        -- At least one byte, so that an empty key has a buffer to wipe.
        let room: Address[Nat8] := allocateBuffer(size + 1);
        case nullCheck(room) of
            when Some(value as buffer: Pointer[Nat8]) do
                var i: Index := 0;
                while i < size do
                    store(positiveOffset(buffer, i), bytes[i]);
                    i := i + 1;
                end while;
                return Key(bytes => buffer, size => size);
            when None do
                abort("Standard.SqlCipher: out of memory");
        end case;
    end;

    function forgetKey(key: Key): Unit is
        let { bytes: Pointer[Nat8], size: Index } := key;
        wipe(bytes, arraySizeInBytes(sizeof(Nat8), size + 1));
        deallocate(bytes);
        return nil;
    end;

    -- Hand the key to SQLCipher, then wipe it.  Right after the open,
    -- before anything reads the file, as the comment of sqlite3_key asks.
    -- A key longer than an Int32 can count is SQLITE_TOOBIG, the code
    -- SQLite gives a value over its size limit: the key may come from a
    -- file or a person, and its length is no reason to stop.
    function applyKey(handle: Address[Unit], key: Key): Int32 is
        let { bytes: Pointer[Nat8], size: Index } := key;
        var rc: Int32 := SQLITE_TOOBIG;
        case valueLength(size) of
            when Some(value as length: Int32) do
                rc := sqlite3_key(handle, @embed(Address[Unit], "(void*)$1", bytes), length);
            when None do
                skip;
        end case;
        wipe(bytes, arraySizeInBytes(sizeof(Nat8), size + 1));
        deallocate(bytes);
        return rc;
    end;

'''

SAFE_PLAIN_BODY = '''    generic [R: Region]
    function openPlainWriter(path: Span[Nat8, R]): Either[SqlError, Connection[Writing]] is
        case bindOpenPlainWriter(path) of
            when Left(left as error: BindError) do
                return Left(left => errorOf(error));
            when Right(right as handle: Handle) do
                return Right(right => Connection(handle => handle, mode => Writing()));
        end case;
    end;

    generic [R: Region]
    function openPlainReader(path: Span[Nat8, R]): Either[SqlError, Connection[Reading]] is
        case bindOpenPlainReader(path) of
            when Left(left as error: BindError) do
                return Left(left => errorOf(error));
            when Right(right as handle: Handle) do
                return Right(right => Connection(handle => handle, mode => Reading()));
        end case;
    end;

'''

SAFE_KEY_BODY = '''    ---
    --- The key
    ---

    record Key: Linear is
        inner: BindKey;
    end;

    generic [R: Region]
    function makeKey(bytes: Span[Nat8, R]): Key is
        return Key(inner => bindMakeKey(bytes));
    end;

    function forgetKey(key: Key): Unit is
        let { inner: BindKey } := key;
        bindForgetKey(inner);
        return nil;
    end;

'''

OPEN_HANDLE_OLD = '''    generic [R: Region]
    function openHandle(path: Span[Nat8, R], flags: OpenFlags): Either[SqlError, Address[Unit]] is
        let name: Pointer[Nat8] := terminated(path);
        let slot: Pointer[Address[Unit]] := slotOf();
        let noVfs: Address[Nat8] := nullPointer();
        let rc: Int32 := sqlite3_open_v2(@embed(Address[Nat8], "$1", name), slotAddress(slot),
            bitsInt32(rawOpenFlags(flags)), noVfs);
        deallocate(name);
        let handle: Address[Unit] := load(slot);
        deallocate(slot);
        if rc /= SQLITE_OK then
            var code: Int32 := rc;
            if not isNull(handle) then
                code := sqlite3_extended_errcode(handle);
                let closed: Int32 := sqlite3_close_v2(handle);
            end if;
            return Left(left => SqlError(code => code));
        end if;
        let timeout: Int32 := sqlite3_busy_timeout(handle, 0);
        return Right(right => handle);
    end;
'''

OPEN_HANDLE_NEW = '''    -- keyed false opens the file without sqlite3_key: no codec is set, and
    -- the file is SQLite's own format; the key is then only wiped.
    generic [R: Region]
    function openHandle(path: Span[Nat8, R], flags: OpenFlags, key: Key, keyed: Bool): Either[SqlError, Address[Unit]] is
        let name: Pointer[Nat8] := terminated(path);
        let slot: Pointer[Address[Unit]] := slotOf();
        let noVfs: Address[Nat8] := nullPointer();
        let rc: Int32 := sqlite3_open_v2(@embed(Address[Nat8], "$1", name), slotAddress(slot),
            bitsInt32(rawOpenFlags(flags)), noVfs);
        deallocate(name);
        let handle: Address[Unit] := load(slot);
        deallocate(slot);
        if rc /= SQLITE_OK then
            forgetKey(key);
            var code: Int32 := rc;
            if not isNull(handle) then
                code := sqlite3_extended_errcode(handle);
                let closed: Int32 := sqlite3_close_v2(handle);
            end if;
            return Left(left => SqlError(code => code));
        else
            var check: Int32 := SQLITE_OK;
            if keyed then
                check := applyKey(handle, key);
            else
                forgetKey(key);
            end if;
            -- SQLCipher notices a wrong key only when it first reads a page.
            -- Reading the schema once here makes a wrong key the error of
            -- this open, and not the error of the first query.
            if check = SQLITE_OK then
                check := runOnce(handle, "SELECT count(*) FROM sqlite_master");
            end if;
            if check /= SQLITE_OK then
                let closed: Int32 := sqlite3_close_v2(handle);
                return Left(left => SqlError(code => check));
            end if;
            let timeout: Int32 := sqlite3_busy_timeout(handle, 0);
            return Right(right => handle);
        end if;
    end;
'''

